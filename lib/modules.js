/**
 * 生成 application.yaml（默认 server.port=5270）
 * @param {string[]} moduleIds
 * @param {string} [dbType]
 */
function generateApplicationYaml(moduleIds, dbType = "mysql") {
  const set = new Set(moduleIds);
  const lines = [
    "# Generated by pangza init",
    "# profile: PANGZA_PROFILE / APP_ENV / NODE_ENV → development",
    "",
    "server:",
    "  port: 5270",
    "  trustProxy: false",
  ];

  if (set.has("redis") || set.has("auth")) {
    lines.push(
      "",
      "redis:",
      "  host: 127.0.0.1",
      "  port: 6379",
      '  password: ""',
      "  db: 0",
      '  keyPrefix: "pangza:"',
      "  mode: standalone",
    );
  }

  if (set.has("orm")) {
    const db = DB_YAML[dbType] || DB_YAML.mysql;
    lines.push(
      "",
      "datasource:",
      "  default:",
      `    type: ${db.type}`,
      "    host: 127.0.0.1",
      `    port: ${db.port}`,
      `    user: ${db.user}`,
      '    password: ""',
      `    database: ${db.database}`,
      "    connectionLimit: 10",
      "",
      "orm:",
      "  logicDelete: true",
      "  logicDeleteField: delete_flag",
      "  logicDeleteValue: 1",
      "  logicNotDeleteValue: 0",
      "  idType: ASSIGN_ID",
      "  mapUnderscoreToCamelCase: true",
      "  mapperLocations: []",
      "  sqlLog:",
      "    enabled: false",
    );
  }

  if (set.has("encrypt")) {
    lines.push("", "# encrypt: 见 @pangza/encrypt");
  }

  if (set.has("schedule")) {
    lines.push("", "# schedule: 任务放 src/schedule，由 Application.scan 加载");
  }

  if (set.has("log")) {
    lines.push("", "# log: registry(Log({ writer })) 可自定义写入");
  }

  if (set.has("auth")) {
    lines.push(
      "",
      "# auth: jwtSecret 等可在 Auth({ ... }) 传入，或后续扩展 yaml",
    );
  }

  lines.push("");
  return lines.join("\n");
}

/**
 * 生成 main.ts：按需 EnableRedis / EnableOrm / Auth / Log
 * @param {string[]} moduleIds
 */
function generateMainTs(moduleIds) {
  const set = new Set(moduleIds);

  const imports = [
    'import "reflect-metadata";',
    'import cors from "cors";',
    'import { json } from "express";',
    'import { Application, Logger } from "@pangza/core";',
  ];

  if (set.has("orm")) {
    imports.push('import { EnableOrm } from "@pangza/orm";');
  }
  if (set.has("redis") || set.has("auth")) {
    imports.push('import Redis, { EnableRedis } from "@pangza/redis";');
  }
  if (set.has("auth")) {
    imports.push('import Auth from "@pangza/auth";');
  }
  if (set.has("log")) {
    imports.push('import Log from "@pangza/log";');
  }

  const notes = [];
  if (set.has("schedule")) {
    notes.push(
      "// Schedule: 在 src/schedule 写任务类，依赖 @pangza/schedule",
    );
  }
  if (set.has("encrypt")) {
    notes.push('// Encrypt: import { AESUtil } from "@pangza/encrypt"');
  }
  if (set.has("validate")) {
    notes.push("// Validate: Controller 参数装饰器已含在 @pangza/core");
  }

  const chain = [
    'Application.registry(Logger({ level: "info" }))',
    "  .registry(cors())",
    "  .registry(json())",
  ];
  if (set.has("orm")) {
    chain.push("  .registry(EnableOrm())");
  }
  if (set.has("redis") || set.has("auth")) {
    chain.push("  .registry(EnableRedis())");
  }
  if (set.has("auth")) {
    chain.push(
      '  .registry(Auth({ ignore: ["/api/pub/**"], redis: Redis }))',
    );
  }
  if (set.has("log")) {
    chain.push("  .registry(Log())");
  }
  chain.push('  .scan("src")');
  chain.push("  .start();");

  return [
    ...imports,
    "",
    ...(notes.length ? [...notes, ""] : []),
    ...chain,
    "",
  ].join("\n");
}

